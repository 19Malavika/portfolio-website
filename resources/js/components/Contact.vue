<script setup>
import { reactive, ref } from 'vue';
import api from '../services/api';

const form = reactive({
  name: '',
  email: '',
  subject: '',
  message: ''
});

const errors = reactive({
  name: '',
  email: '',
  subject: '',
  message: ''
});

const isSubmitting = ref(false);
const feedback = reactive({
  type: '',
  message: ''
});

const validate = () => {
  let isValid = true;
  errors.name = '';
  errors.email = '';
  errors.subject = '';
  errors.message = '';

  if (!form.name.trim()) {
    errors.name = 'Name is required.';
    isValid = false;
  }

  const emailRegex = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;
  if (!form.email.trim()) {
    errors.email = 'Email is required.';
    isValid = false;
  } else if (!emailRegex.test(form.email)) {
    errors.email = 'Please enter a valid email address.';
    isValid = false;
  }

  if (!form.subject.trim()) {
    errors.subject = 'Subject is required.';
    isValid = false;
  }

  if (!form.message.trim()) {
    errors.message = 'Message is required.';
    isValid = false;
  } else if (form.message.trim().length < 10) {
    errors.message = 'Message must be at least 10 characters.';
    isValid = false;
  }

  return isValid;
};

const handleSubmit = async () => {
  if (!validate()) return;

  isSubmitting.value = true;
  feedback.type = '';
  feedback.message = '';

  try {
    const res = await api.post('/contact', form);
    feedback.type = 'success';
    feedback.message = res.data.message || 'Thank you! Your message has been sent successfully.';
    
    // Clear form
    form.name = '';
    form.email = '';
    form.subject = '';
    form.message = '';
  } catch (err) {
    feedback.type = 'error';
    if (err.response && err.response.data && err.response.data.message) {
      feedback.message = err.response.data.message;
    } else {
      feedback.message = 'An unexpected error occurred while sending your message. Please try again or email directly.';
    }
  } finally {
    isSubmitting.value = false;
  }
};
</script>

